std::string TunCompiler::CompileConfig(const std::string& base_yaml, const TunCompilerOptions& options) {
    std::ostringstream oss;
    oss << "# Generated by ClashWin Tun & Agreement Compiler\n";
    oss << "mixed-port: 10801\n";
    oss << "port: 7890\n";
    oss << "socks-port: 7891\n";
    oss << "allow-lan: false\n";
    oss << "mode: rule\n";
    oss << "log-level: info\n";
    oss << "external-controller: 127.0.0.1:9098\n";

    // 1. 顶层 ipv6 配置 (防泄漏最高铁律：开启 TUN 时强制为 true)
    if (options.enable_tun) {
        oss << "ipv6: true\n\n";
    } else {
        oss << "ipv6: " << (options.user_ipv6 ? "true" : "false") << "\n\n";
    }

    // 2. TUN 网卡配置
    if (options.enable_tun) {
        oss << "tun:\n";
        oss << "  enable: true\n";
        oss << "  stack: gvisor\n";
        oss << "  auto-route: true\n";
        oss << "  auto-detect-interface: true\n";
        oss << "  inet6-address:\n";
        oss << "    - \"fdfe:dcba:9876::1/126\"\n\n";
    } else {
        oss << "tun:\n";
        oss << "  enable: false\n\n";
    }

    // 3. DNS 配置
    oss << "dns:\n";
    oss << "  enable: true\n";
    if (options.enable_tun) {
        oss << "  enhanced-mode: fake-ip\n";
        oss << "  fake-ip-range: \"198.18.0.1/16\"\n";
        if (options.user_ipv6) {
            oss << "  fake-ip-range6: \"2001:2::0/64\"\n";
        }
        oss << "  ipv6: " << (options.user_ipv6 ? "true" : "false") << "\n";
        oss << "  fake-ip-filter:\n";
        for (const auto& filter : GetDefaultFakeIpFilters()) {
            oss << "    - \"" << filter << "\"\n";
        }
    } else {
        oss << "  ipv6: " << (options.user_ipv6 ? "true" : "false") << "\n";
    }
    oss << "\n";

    // 4. 提取原 base_yaml 中的 proxies 定义 (若存在)
    std::vector<std::string> proxy_names;
    bool in_proxies = false;
    std::string proxies_block;

    std::istringstream iss(base_yaml);
    std::string line;
    std::regex name_regex(R"(^\s*-\s*name:\s*[\"']?([^\"'\r\n]+)[\"']?)");

    while (std::getline(iss, line)) {
        if (line.starts_with("proxies:")) {
            in_proxies = true;
            proxies_block += line + "\n";
            continue;
        }
        if (in_proxies) {
            if (!line.empty() && !line.starts_with(" ") && !line.starts_with("\t")) {
                in_proxies = false;
            } else {
                proxies_block += line + "\n";
                std::smatch match;
                if (std::regex_search(line, match, name_regex) && match.size() > 1) {
                    proxy_names.push_back(match[1].str());
                }
            }
        }
    }

    if (!proxies_block.empty()) {
        oss << proxies_block << "\n";
    } else {
        // 兜底示例代理
        oss << "proxies:\n";
        oss << "  - name: \"DIRECT\"\n";
        oss << "    type: direct\n\n";
        proxy_names.push_back("DIRECT");
    }

    // 5. 注入单一 PROXY 组与 PROXY__METRICS 测量组
    oss << "proxy-groups:\n";
    oss << "  - name: PROXY\n";
    oss << "    type: select\n";
    oss << "    proxies:\n";
    for (const auto& name : proxy_names) {
        oss << "      - \"" << name << "\"\n";
    }
    oss << "      - DIRECT\n";

    oss << "  - name: PROXY__METRICS\n";
    oss << "    type: url-test\n";
    oss << "    url: " << options.default_latency_test << "\n";
    oss << "    interval: 300\n";
    oss << "    proxies:\n";
    for (const auto& name : proxy_names) {
        oss << "      - \"" << name << "\"\n";
    }
    oss << "\n";

    // 6. 注入 rule-providers (GFWList)
    oss << "rule-providers:\n";
    oss << "  gfwlist:\n";
    oss << "    type: http\n";
    oss << "    behavior: domain\n";
    oss << "    url: \"https://cdn.jsdelivr.net/gh/Loyalsoldier/clash-rules@release/gfw.txt\"\n";
    oss << "    path: \"./ruleset/gfwlist.yaml\"\n";
    oss << "    interval: 86400\n";
    oss << "    proxy: PROXY\n\n";

    // 7. 注入 rules 规则树
    oss << "rules:\n";
    // 7.1 GFWList 规则集
    oss << "  - RULE-SET,gfwlist,PROXY\n";

    // 7.2 DNS fallback 境外 DoH 防投毒上游强制走代理
    oss << "  - IP-CIDR,8.8.8.8/32,PROXY,no-resolve\n";
    oss << "  - IP-CIDR,8.8.4.4/32,PROXY,no-resolve\n";
    oss << "  - IP-CIDR,1.1.1.1/32,PROXY,no-resolve\n";
    oss << "  - IP-CIDR,1.0.0.1/32,PROXY,no-resolve\n";

    // 7.3 本地局域网与 IPv6 直连规则 (防回环死锁)
    for (const auto& rule : GetMandatoryDirectRules()) {
        oss << "  - " << rule << "\n";
    }

    // 7.4 IPv6 兜底与 MATCH 终态规则
    if (options.rule_fallback == "proxy") {
        oss << "  - MATCH,PROXY\n";
    } else {
        // 刻意不加 no-resolve 保证 IPv6 域名解析命中并由 mmdb 分流
        oss << "  - GEOIP,CN,DIRECT\n";
        oss << "  - IP-CIDR6,::/0,PROXY\n";
        oss << "  - MATCH,DIRECT\n";
    }

    return oss.str();
}

